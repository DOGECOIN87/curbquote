import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildPublicAssets } from './build.mjs';
import { SECURITY_HEADERS, projectRoot } from '../lib/web.mjs';
import { map3dConfig } from '../api/map3d.js';
import { leadConfig } from '../api/lead.js';

// GitHub Pages serves files only: no API routes and no response headers. The page asks Census directly
// (JSONP), reads the 3D credential and Alco's lead email from config.js, and carries its security policy in meta tags.
const CENSUS = 'https://geocoding.geo.census.gov/geocoder/locations/onelineaddress';
export function pagesPolicy() {
  return SECURITY_HEADERS['Content-Security-Policy']
    .replace("script-src 'self'", `script-src 'self' ${CENSUS}`)
    .replace(/; frame-ancestors [^;]+/, '');   // Ignored, with a warning, when delivered by a meta tag.
}
export async function buildPagesSite(destination = join(projectRoot, 'dist-pages'), env = process.env) {
  await buildPublicAssets(destination);
  const config = map3dConfig(env);
  await writeFile(join(destination, 'config.js'), `/** Generated by scripts/build-pages.mjs for the static GitHub Pages demo. */\nexport const STATIC_SITE = true;\nexport const STATIC_MAP3D = ${JSON.stringify(config)};\nexport const STATIC_LEAD = ${JSON.stringify({ email: leadConfig(env).email })};\n`);
  const page = join(destination, 'index.html'), html = await readFile(page, 'utf8');
  const meta = `<meta http-equiv="Content-Security-Policy" content="${pagesPolicy()}">\n  <meta name="referrer" content="${SECURITY_HEADERS['Referrer-Policy']}">\n  `;
  if (!html.includes('<meta name="viewport"')) throw new Error('index.html changed; update build-pages.mjs.');
  await writeFile(page, html.replace('<meta name="viewport"', `${meta}<meta name="viewport"`));
  await writeFile(join(destination, '.nojekyll'), '');
  return config;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const config = await buildPagesSite();
  console.log(`Built the static GitHub Pages demo in dist-pages/. 3D view: ${config.configured ? config.provider : 'off (no credential set)'}.`);
}
